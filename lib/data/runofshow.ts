// ---------- ช่วงของวัน (คำนวณจากเวลาเริ่มของคิว — ไม่ฮาร์ดโค้ดแยกต่อคิว) ----------

export type Section = "morning" | "lunch" | "afternoon";
export const SECTION_LABEL: Record<Section, string> = { morning: "ภาคเช้า", lunch: "พักเที่ยง", afternoon: "ภาคบ่าย" };

/** นาทีนับจาก 00:00 ของเวลาเริ่ม ("8.00–8.10" / "12:00–13.00" / "17:30") · อ่านไม่ได้/null → null */
export function startMinutes(time: Field<string>): number | null {
  if (!time) return null;
  const m = /^\s*(\d{1,2})[.:](\d{2})/.exec(time);
  if (!m) return null;
  return Number(m[1]) * 60 + Number(m[2]);
}

/** ก่อน 12:00 = เช้า · 12:00–12:59 = พักเที่ยง · 13:00 เป็นต้นไป = บ่าย */
export function sectionOf(startMin: number): Section {
  if (startMin < 12 * 60) return "morning";
  if (startMin < 13 * 60) return "lunch";
  return "afternoon";
}

